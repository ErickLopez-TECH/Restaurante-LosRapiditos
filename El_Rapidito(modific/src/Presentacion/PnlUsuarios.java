    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        
        
        String idTexto = txtId.getText().trim();
        String nombre = txtNombre.getText();
        String apellidos = txtApellidos.getText();
        String cedula = txtCedula.getText();
        String telefono = txtTelefono.getText();
        String correo = txtCorreo.getText();
        String dirreccion = txtDireccion.getText();
        String nombreUser = txtNombreUser.getText();
        String clave = new String(txtClave.getPassword());
        int rol = cmbRol.getSelectedIndex();
        int estado = cmbEstado.getSelectedIndex();
        
        if (idTexto.isEmpty()) {
            // 1. NUEVA CAJA: SQLite autogenera la clave primaria
            ObjUsuario miUsuario = new ObjUsuario(cedula, nombre, apellidos, dirreccion, telefono, correo, nombreUser,  clave, estado, rol);
            almacen.agregarUser(miUsuario); 
        } else {
            // 2. EDITAR User: Actualizamos en SQLite con el ID existente
            int id = Integer.parseInt(idTexto);
            ObjUsuario miUser = new ObjUsuario(id, cedula, nombre, apellidos, dirreccion, telefono, correo, nombreUser, clave, estado, rol);
            almacen.editarUser(miUser); // Descomentado
            JOptionPane.showMessageDialog(this, "se guardo: " + rol);
        }
        
        tblLista.setModel(almacen.mostrarUser());
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
       if(!txtId.getText().equals("")){
            int id = Integer.parseInt(txtId.getText());
            
            
            //ya tengo los datos
            ObjUsuario miUser = misMetodos.buscarUserPorId(id);
            
            if (miUser != null) {
                txtNombre.setText(miUser.getNombre());
                txtApellidos.setText(miUser.getApellidos());
                txtCedula.setText(miUser.getCedula());
                txtTelefono.setText(miUser.getTelefono());
                txtCorreo.setText(miUser.getCorreo());
                txtDireccion.setText(miUser.getDireccion());
                txtNombreUser.setText(miUser.getNombreUser());
                txtClave.setText(miUser.getClave());
                cmbRol.setSelectedIndex(miUser.getRol());
                cmbEstado.setSelectedIndex(miUser.getEstado());
             } else {
                // Si devuelve null, significa que no existe caja con ese ID
                JOptionPane.showMessageDialog(this, "No se encontró ningun user con el ID: " + id);
                txtNombre.setText("");
                //txtUbicacion.setText("");
        }
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarActionPerformed
        // TODO add your handling code here:
        
         if (!txtId.getText().trim().equals("")) {
            int id = Integer.parseInt(txtId.getText().trim());

            almacen.quitarUser(id);

            // Refrescar lista y limpiar campos
           // lstLista.setModel(almacen.mostrarCajas());
            txtId.setText("");
            txtNombre.setText("");
            tblLista.setModel(almacen.mostrarUser());
        }
  
    }//GEN-LAST:event_btnBorrarActionPerformed

